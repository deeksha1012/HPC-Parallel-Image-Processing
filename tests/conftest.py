"""
Pytest configuration and shared test fixtures for the HPC Image Processing test suite.
"""

import os
import pytest
import numpy as np
import pandas as pd

from src.benchmark import run_benchmark


@pytest.fixture(scope="session")
def tiny_images() -> list[tuple[str, np.ndarray]]:
    """Generate 4 tiny synthetic RGB test images of shape (48, 64, 3) for fast unit testing."""
    rng = np.random.default_rng(0)
    images = []
    for i in range(1, 5):
        arr = rng.integers(0, 256, size=(48, 64, 3), dtype=np.uint8)
        images.append((f"img_{i}.png", arr))
    return images


@pytest.fixture(scope="session")
def params() -> dict[str, int | float]:
    """Standard filter parameter dictionary for test cases."""
    return {"kernel_size": 5, "sigma": 1.0}


@pytest.fixture(scope="session")
def tiny_benchmark_df(
    tiny_images: list[tuple[str, np.ndarray]],
    params: dict[str, int | float],
) -> pd.DataFrame:
    """
    Session-scoped real benchmark DataFrame generated by executing run_benchmark
    on tiny images with 2 workers and 1 repeat. Avoids hardcoded fake numbers.
    """
    cpu_count = os.cpu_count() or 1
    if cpu_count < 2:
        pytest.skip("Test requires at least 2 CPU cores for parallel benchmarking.")

    df, _ = run_benchmark(
        images=tiny_images,
        params=params,
        worker_counts=[2],
        repeats=1,
    )
    return df
